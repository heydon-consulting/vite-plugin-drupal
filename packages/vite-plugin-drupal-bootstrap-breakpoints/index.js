import fs from 'node:fs';
import path from 'node:path';
import { preprocessCSS } from 'vite';
import { extensionDirs, findExtensions } from 'vite-plugin-drupal-libraries';

/**
 * Writes a theme's <theme>.breakpoints.yml from Bootstrap's breakpoints.
 *
 * Bootstrap's compiled CSS lists its grid breakpoints as custom properties
 * (Bootstrap 4: `:root { --breakpoint-sm: 576px; ... }`, from
 * $grid-breakpoints). A theme opts in from its .info.yml:
 *
 *   vite:
 *     breakpoints:
 *       # The stylesheet that compiles Bootstrap, relative to the theme.
 *       css: scss/bootstrap.scss
 *       # Optional: the custom property prefix (Bootstrap 5.3:
 *       # bs-breakpoint) and the multipliers of every breakpoint.
 *       prefix: breakpoint
 *       multipliers: ['1x', '2x']
 *
 * The stylesheet is compiled like any other (Vite's CSS pipeline, so the
 * theme's preloaded variables apply), and each breakpoint becomes
 * `<theme>.<name>` with a mobile-first `all and (min-width: ...)` query,
 * weighted in the order Bootstrap lists them. The file is written on every
 * build and dev server start, and again in dev when a file the stylesheet uses
 * changes; only when its contents change. Drupal caches breakpoints, so run
 * `drush cr` after it changes.
 */
export default function bootstrapBreakpoints({
  root = process.cwd(),
  dirs = extensionDirs(root),
} = {}) {
  let config;
  // Theme directory => { name, css, prefix, multipliers, file, deps }.
  const themes = new Map();

  const generate = async (theme) => {
    const { name } = theme;
    const result = await preprocessCSS(fs.readFileSync(theme.css, 'utf8'), theme.css, config);
    theme.deps = new Set([theme.css, ...(result.deps ?? [])].map((file) => path.resolve(file)));
    const breakpoints = [];
    const pattern = new RegExp(`--${theme.prefix}-([a-z0-9_-]+)\\s*:\\s*([^;}]+)`, 'gi');
    for (const [, key, value] of result.code.matchAll(pattern)) {
      if (!breakpoints.some((b) => b.key === key)) {
        breakpoints.push({ key, value: value.trim() === '0' ? '0px' : value.trim() });
      }
    }
    const source = path.relative(path.dirname(theme.file), theme.css).split(path.sep).join('/');
    if (!breakpoints.length) {
      throw new Error(`bootstrap-breakpoints: no --${theme.prefix}-* custom properties in the CSS compiled from ${name}'s ${source}.`);
    }

    const yaml = [
      `# Generated by vite-plugin-drupal-bootstrap-breakpoints from ${source}`,
      `# (--${theme.prefix}-* in the compiled CSS). Don't edit: change the breakpoints`,
      '# there, or vite.breakpoints in the .info.yml, and run the build.',
      ...breakpoints.flatMap(({ key, value }, weight) => [
        `${name}.${key}:`,
        `  label: ${key}`,
        `  mediaQuery: 'all and (min-width: ${value})'`,
        `  weight: ${weight}`,
        '  multipliers:',
        ...theme.multipliers.map((multiplier) => `    - ${multiplier}`),
      ]),
    ].join('\n') + '\n';

    if (!fs.existsSync(theme.file) || fs.readFileSync(theme.file, 'utf8') !== yaml) {
      fs.writeFileSync(theme.file, yaml);
      config.logger.info(`bootstrap-breakpoints: wrote ${path.relative(root, theme.file)} `
        + `(${breakpoints.map((b) => `${b.key} ${b.value}`).join(', ')}); run drush cr.`);
    }
  };

  const generateAll = () => Promise.all([...themes.values()].map(generate));

  return {
    name: 'bootstrap-breakpoints',

    configResolved(resolvedConfig) {
      config = resolvedConfig;
      for (const [key, { name, dir, info }] of findExtensions(root, dirs)) {
        const options = info.vite?.breakpoints;
        if (info.type !== 'theme' || !options) {
          continue;
        }
        if (typeof options.css !== 'string') {
          throw new Error(`bootstrap-breakpoints: ${name}.info.yml vite.breakpoints needs a css: stylesheet.`);
        }
        const css = path.resolve(dir, options.css);
        if (!fs.existsSync(css)) {
          throw new Error(`bootstrap-breakpoints: ${name}.info.yml vite.breakpoints.css ${options.css} does not exist.`);
        }
        themes.set(key, {
          name,
          css,
          prefix: options.prefix ?? 'breakpoint',
          multipliers: [options.multipliers ?? ['1x']].flat().map(String),
          file: path.join(dir, `${name}.breakpoints.yml`),
          deps: new Set(),
        });
      }
    },

    async buildStart() {
      if (config.command === 'build') {
        await generateAll();
      }
    },

    async configureServer(server) {
      await generateAll();
      server.watcher.on('change', (file) => {
        const changed = path.resolve(file);
        for (const theme of themes.values()) {
          if (theme.deps.has(changed)) {
            generate(theme).catch((error) => config.logger.error(error.message));
          }
        }
      });
    },
  };
}
