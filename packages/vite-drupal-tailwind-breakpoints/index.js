import fs from 'node:fs';
import path from 'node:path';
import { __unstable__loadDesignSystem as loadDesignSystem } from '@tailwindcss/node';
import { extensionDirs, findExtensions } from 'vite-drupal-libraries';

/**
 * Writes a theme's <theme>.breakpoints.yml from Tailwind's breakpoints.
 *
 * Tailwind's breakpoints are the `--breakpoint-*` theme variables: its
 * defaults, and any a stylesheet sets in `@theme`. A theme opts in from its
 * .info.yml:
 *
 *   vite:
 *     breakpoints:
 *       # The stylesheet that imports Tailwind, relative to the theme.
 *       css: css/style.css
 *       # Optional: the theme variable namespace and the multipliers of
 *       # every breakpoint.
 *       prefix: breakpoint
 *       multipliers: ['1x', '2x']
 *
 * Tailwind compiles breakpoints into media queries rather than outputting
 * them as custom properties, so they're read from the stylesheet's resolved
 * theme (Tailwind's own loader: its @import and @theme, not Vite's
 * pipeline). Each breakpoint becomes `<theme>.<name>` with a mobile-first
 * `all and (min-width: ...)` query, weighted in Tailwind's order. The file is
 * written on every build and dev server start, and again in dev when a CSS
 * file in the theme changes; only when its contents change. Drupal caches
 * breakpoints, so run `drush cr` after it changes.
 */
export default function drupalTailwindBreakpoints({
  root = process.cwd(),
  dirs = extensionDirs(root),
} = {}) {
  let config;
  // Theme directory => { name, dir, css, prefix, multipliers, file }.
  const themes = new Map();

  const generate = async (theme) => {
    const { name } = theme;
    const design = await loadDesignSystem(fs.readFileSync(theme.css, 'utf8'), { base: path.dirname(theme.css) });
    const breakpoints = [...design.theme.namespace(`--${theme.prefix}`)]
      .filter(([key]) => key !== null)
      .map(([key, value]) => ({ key, value: value.trim() === '0' ? '0px' : value.trim() }));
    const source = path.relative(path.dirname(theme.file), theme.css).split(path.sep).join('/');
    if (!breakpoints.length) {
      throw new Error(`drupal-tailwind-breakpoints: no --${theme.prefix}-* theme variables in ${name}'s ${source}.`);
    }

    const yaml = [
      '# Generated by vite-drupal-tailwind-breakpoints from',
      `# ${source} (Tailwind's --${theme.prefix}-* theme variables). Don't edit:`,
      '# change the breakpoints there, or vite.breakpoints in the .info.yml, and',
      '# run the build.',
      ...breakpoints.flatMap(({ key, value }, weight) => [
        `${name}.${key}:`,
        `  label: ${key}`,
        `  mediaQuery: 'all and (min-width: ${value})'`,
        `  weight: ${weight}`,
        '  multipliers:',
        ...theme.multipliers.map((multiplier) => `    - ${multiplier}`),
      ]),
    ].join('\n') + '\n';

    if (!fs.existsSync(theme.file) || fs.readFileSync(theme.file, 'utf8') !== yaml) {
      fs.writeFileSync(theme.file, yaml);
      config.logger.info(`drupal-tailwind-breakpoints: wrote ${path.relative(root, theme.file)} `
        + `(${breakpoints.map((b) => `${b.key} ${b.value}`).join(', ')}); run drush cr.`);
    }
  };

  const generateAll = () => Promise.all([...themes.values()].map(generate));

  return {
    name: 'drupal-tailwind-breakpoints',

    configResolved(resolvedConfig) {
      config = resolvedConfig;
      for (const [key, { name, dir, info }] of findExtensions(root, dirs)) {
        const options = info.vite?.breakpoints;
        if (info.type !== 'theme' || !options) {
          continue;
        }
        if (typeof options.css !== 'string') {
          throw new Error(`drupal-tailwind-breakpoints: ${name}.info.yml vite.breakpoints needs a css: stylesheet.`);
        }
        const css = path.resolve(dir, options.css);
        if (!fs.existsSync(css)) {
          throw new Error(`drupal-tailwind-breakpoints: ${name}.info.yml vite.breakpoints.css ${options.css} does not exist.`);
        }
        themes.set(key, {
          name,
          dir,
          css,
          prefix: options.prefix ?? 'breakpoint',
          multipliers: [options.multipliers ?? ['1x']].flat().map(String),
          file: path.join(dir, `${name}.breakpoints.yml`),
        });
      }
    },

    async buildStart() {
      if (config.command === 'build') {
        await generateAll();
      }
    },

    async configureServer(server) {
      await generateAll();
      server.watcher.on('change', (file) => {
        const changed = path.resolve(file);
        for (const theme of themes.values()) {
          if (changed.endsWith('.css') && changed.startsWith(theme.dir + path.sep)) {
            generate(theme).catch((error) => config.logger.error(error.message));
          }
        }
      });
    },
  };
}
